/**
 * What the Sql and documents engines cover against EF Core (#819): one page, written from the two lists the gate already checks, so the
 * page cannot say something the lists do not.
 *
 * - engine-projects.mjs: the module files the Showcase's engine projects leave out, each for its engine and why;
 * - engine-suites.mjs: the files and single tests the Showcase suite leaves out on each engine, and the counts it runs.
 *
 * The page sorts every exclusion into the kind that decides what is done with it: not measured (the test's own code is bound to EF Core),
 * EF Core only (a feature read through an IQueryable), by design on the documents engine (a relation kept as a key), the real gaps a
 * measurement found (each with its issue), and the smaller kinds.
 *
 *   node scripts/engine-coverage.mjs           writes the page
 *   node scripts/engine-coverage.mjs --check   exits 1 when the page differs from what the lists say
 *   node --test scripts/engine-coverage.test.mjs
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ALLOWED_EXCLUSIONS, PROJECT_REASONS } from './engine-projects.mjs';
import { ALLOWED_FILE_EXCLUSIONS, ALLOWED_TEST_EXCLUSIONS, ENGINE_SUITES, SUITE_DIR, SUITE_REASONS, engineOf, suiteCount, testMethods } from './engine-suites.mjs';

/** Where the page is written, from the repository's root. */
export const COVERAGE_PAGE = 'Pragmatic.Persistence/docs/22-engine-coverage.md';

const ENGINES = ['Sql', 'Documents'];
const suitePath = (path) => path.slice(SUITE_DIR.length + 1);
const isNoNavigation = (reason) => reason.startsWith(PROJECT_REASONS.NO_NAVIGATION) || reason === SUITE_REASONS.NO_NAVIGATION;
const engines = (list) => (list.length === ENGINES.length ? 'both' : list.join(', '));

/**
 * Real gaps that no exclusion records, because no test of the Showcase suite uses the feature: written here by hand, each with the
 * issue that implements it on the engines, and removed when that issue closes.
 */
const GAPS_NO_SUITE_TEST_EXERCISES = [];

/**
 * The page, as Markdown.
 *
 * @param {(path: string) => string | null} read a source's text by its path from the root; null when there is no such file
 * @param {string[]} suiteFiles the EF Core suite's sources, paths from the root
 */
export function coveragePage(read, suiteFiles) {
  const methodsOf = (path) => testMethods(read(path) ?? '').length;
  const files = Object.entries(ALLOWED_FILE_EXCLUSIONS);
  const tests = Object.entries(ALLOWED_TEST_EXCLUSIONS);
  const modules = Object.entries(ALLOWED_EXCLUSIONS);

  const lines = [];
  const add = (...l) => lines.push(...l);

  add(
    '# What the engines cover',
    '',
    '<!-- Generated by scripts/engine-coverage.mjs from scripts/engine-projects.mjs and scripts/engine-suites.mjs. Do not edit: change the',
    '     lists and run `node scripts/engine-coverage.mjs`. The gate fails when this page differs from what the lists say. -->',
    '',
    'The Showcase runs on EF Core, and the same modules and the same integration suite run on the Sql engine and on the documents engine',
    '([Engines](21-engines.md)). What an engine copy leaves out is listed in the gate, each exclusion with its reason, and nothing is left',
    'out silently. This page is those lists, sorted by the kind of gap each one is.',
    '',
    '**The direction for the beta** (owner, 2026-11-16): the engines are brought level with EF Core, not only measured. Each real gap the',
    'measurement finds gets an issue of its own that implements it on both engines; the EF Core-only features and the documents engine\'s',
    'relations kept as keys are revisited with that goal, rather than kept as exclusions by default (#819).',
    '',
    '## The suite on each engine',
    '',
    '| Engine | Test methods run | Of the EF Core suite\'s | Files left out | Single tests left out |',
    '|---|---|---|---|---|',
  );
  for (const project of ENGINE_SUITES) {
    const c = suiteCount(project, suiteFiles, read);
    add(`| ${engineOf(project)} | **${c.runs}** | ${c.all} | ${c.files} | ${c.filtered} |`);
  }

  // 1. Not measured.
  const onEf = files.filter(([, a]) => a.reason === SUITE_REASONS.TEST_ON_EF).map(([path]) => path).sort();
  const onEfMethods = onEf.reduce((sum, path) => sum + methodsOf(path), 0);
  const onEfTestFiles = onEf.filter((path) => methodsOf(path) > 0).length;
  const others = onEf.length - onEfTestFiles;
  add('', '## 1. Not measured: the test is bound to EF Core', '');
  if (onEf.length === 0) {
    add(
      'None. Every test once left out because it read or prepared rows through EF Core (owner decision, 2026-11-06) is written through',
      'the engine-neutral surface now, the boundary\'s repositories or the session, and runs on the engines (#819).',
    );
  } else {
    add(
      `**${onEfTestFiles} test files, ${onEfMethods} test methods**${others > 0 ? ` (and ${others} source they share)` : ''}, left out on both engines because the test itself reads or prepares rows through`,
      'EF Core, not because the engines are known to lack the feature (owner decision, 2026-11-06). Whether the engines support what these',
      'exercise is unknown until each file is rewritten through the engine-neutral surface: the boundary\'s repositories, or the session.',
      'A test that then fails on an engine is a real gap, with an issue of its own.',
      '',
      '| File | Test methods |',
      '|---|---|',
      ...onEf.map((path) => `| \`${suitePath(path)}\` | ${methodsOf(path)} |`),
    );
  }

  // 2. EF Core only.
  const efOnlyModules = modules.filter(([, a]) => a.reason === PROJECT_REASONS.EF_ONLY).map(([path]) => path).sort();
  const efOnlySuite = files.filter(([, a]) => a.reason === SUITE_REASONS.EF_ONLY).sort(([a], [b]) => a.localeCompare(b));
  add(
    '',
    '## 2. EF Core only: read through an IQueryable',
    '',
    'The engines read through their own query model, not `IQueryable`, so these module files are left out on both (#363), and the suite',
    'files that exercise them with them. The owner decided each feature on 2026-11-22 (#819). The grid filter search and the generated',
    'DevExpress grid adapter, once listed here, run on the engines (#946, #947). `CountAmenitiesAction` stays EF Core only: it injects',
    'the boundary\'s `DbContext`, which is EF Core\'s by construction.',
    '',
    '| Module file | Engines |',
    '|---|---|',
    ...efOnlyModules.map((path) => `| \`${path}\` | ${engines(ALLOWED_EXCLUSIONS[path].engines)} |`),
    '',
    '| Suite file | Test methods | Follows from |',
    '|---|---|---|',
    ...efOnlySuite.map(([path, a]) => `| \`${suitePath(path)}\` | ${methodsOf(path)} | ${(a.follows ?? []).map((f) => `\`${f.split('/').pop()}\``).join(', ')} |`),
  );

  // 3. By design on the documents engine.
  const noNavModules = modules.filter(([, a]) => isNoNavigation(a.reason)).map(([path]) => path).sort();
  const noNavTests = tests.filter(([, a]) => a.reason === SUITE_REASONS.NO_NAVIGATION);
  const noNavFiles = files.filter(([, a]) => a.reason === SUITE_REASONS.NO_NAVIGATION).map(([path]) => path).sort();
  const byFile = new Map();
  for (const [name, a] of noNavTests) byFile.set(a.file, [...(byFile.get(a.file) ?? []), name.split('.').pop()]);
  add(
    '',
    '## 3. By design on the documents engine: a relation is kept as a key',
    '',
    'A document keeps a relation as the related row\'s key (#479), so the documents engine refuses a `[LoadEntity]` with an `Include`',
    '(PRAG3111) and a write that cascades through a navigation (PRAG3112). The module files that need them are left out there, and the',
    `suite's tests that call them: **${noNavTests.length} single tests** in ${byFile.size} files, and ${noNavFiles.length} files whole.`,
    '',
    '| Module file | Refused as |',
    '|---|---|',
    ...noNavModules.map((path) => `| \`${path}\` | ${/PRAG\d+/.exec(ALLOWED_EXCLUSIONS[path].reason)?.[0] ?? ''} |`),
    '',
    '| Suite file | Single tests left out |',
    '|---|---|',
    ...[...byFile].sort(([a], [b]) => a.localeCompare(b)).map(([path, methods]) => `| \`${suitePath(path)}\` | ${methods.length} |`),
    ...noNavFiles.map((path) => `| \`${suitePath(path)}\` | the whole file, ${methodsOf(path)} test methods |`),
  );

  // Real gaps: what a measurement of kind 1 found missing, each with the issue that implements it.
  const isGap = (reason) => reason.startsWith(SUITE_REASONS.REAL_GAP);
  const gapFiles = files.filter(([, a]) => isGap(a.reason));
  const gapTests = tests.filter(([, a]) => isGap(a.reason));
  const gapReasons = [...new Set([...gapFiles, ...gapTests].map(([, a]) => a.reason))].sort();
  add(
    '',
    '## 4. Real gaps, each with its issue',
    '',
    'What measuring kind 1 found missing on an engine: the feature, not the test. Each gap has an issue that implements it there, and',
    'its exclusion goes when the issue closes.',
    '',
  );
  if (gapReasons.length === 0 && GAPS_NO_SUITE_TEST_EXERCISES.length === 0) add('None found yet.');
  for (const gap of GAPS_NO_SUITE_TEST_EXERCISES) add(gap, '');
  for (const reason of gapReasons) {
    add(`**${reason.slice(SUITE_REASONS.REAL_GAP.length)}**`, '');
    for (const [path, a] of gapFiles.filter(([, a]) => a.reason === reason).sort(([x], [y]) => x.localeCompare(y)))
      add(`- \`${suitePath(path)}\` (${engines(a.engines)}), ${methodsOf(path)} test methods`);
    for (const [name, a] of gapTests.filter(([, a]) => a.reason === reason).sort(([x], [y]) => x.localeCompare(y)))
      add(`- \`${suitePath(a.file)}\`: \`${name.split('.').pop()}\` (${engines(a.engines)})`);
    add('');
  }

  // The smaller kinds.
  const best = tests.filter(([, a]) => a.reason === SUITE_REASONS.LIMIT_BEST_EFFORT);
  const provider = files.filter(([, a]) => a.reason === SUITE_REASONS.EF_PROVIDER).sort(([x], [y]) => x.localeCompare(y));
  const copyNamespace = files.filter(([, a]) => a.reason === SUITE_REASONS.COPY_NAMESPACE).sort(([x], [y]) => x.localeCompare(y));
  const compiledAtCall = tests.filter(([, a]) => a.reason === SUITE_REASONS.COMPILED_AT_CALL);
  const noTransaction = tests.filter(([, a]) => a.reason === SUITE_REASONS.NO_TRANSACTION).sort(([x], [y]) => x.localeCompare(y));
  const onSql = files.filter(([, a]) => a.reason === SUITE_REASONS.TEST_ON_SQL).map(([path]) => path).sort();
  const replaced = files.filter(([, a]) => [SUITE_REASONS.REPLACED, SUITE_REASONS.REPLACED_FIXTURE, SUITE_REASONS.REPLACED_COMMITS, SUITE_REASONS.REPLACED_JOB_STORE].includes(a.reason));
  const wiring = modules.filter(([, a]) => a.reason === PROJECT_REASONS.HOST_WIRING).map(([path]) => path);
  add(
    '',
    '## 5. The smaller kinds',
    '',
    '**A per-entity limit is best effort on the documents engine** (owner decision, 2026-10-26, #397): it is counted before the write, with',
    'no serializable transaction, so concurrent adds can cross it.',
    '',
    ...best.map(([name, a]) => `- \`${suitePath(a.file)}\`: \`${name.split('.').pop()}\` (${engines(a.engines)})`),
    '',
    '**The test is of a mechanism of the EF Core provider**, which the engines do not have by construction:',
    '',
    ...provider.map(([path, a]) => `- \`${suitePath(path)}\` (${engines(a.engines)}), ${methodsOf(path)} test methods`),
    '',
    '**The test names a type the generator puts in the assembly\'s namespace**, and an engine copy of a module is another assembly:',
    '',
    ...copyNamespace.map(([path, a]) => `- \`${suitePath(path)}\` (${engines(a.engines)}), ${methodsOf(path)} test methods`),
    '',
    '**The test calls a bulk write itself**, which the Sql engine compiles where it is called, and the test assembly is not one its',
    'generator runs on. The bulk write is tested where it is compiled, in `Pragmatic.Persistence.Sql.Tests`:',
    '',
    ...compiledAtCall.map(([name, a]) => `- \`${suitePath(a.file)}\`: \`${name.split('.').pop()}\` (${engines(a.engines)})`),
    '',
    '**The test opens a transaction**, and the documents host\'s MongoDB is standalone: it runs none, and the unit of work refuses to',
    'begin one. What a commit and an abort report on that engine is tested on a replica set, in `DocCommitHooksTests`:',
    '',
    ...noTransaction.map(([name, a]) => `- \`${suitePath(a.file)}\`: \`${name.split('.').pop()}\` (${engines(a.engines)})`),
    '',
    '**The test reads or migrates PostgreSQL itself**, and the documents host has none:',
    '',
    ...onSql.map((path) => `- \`${suitePath(path)}\` (${engines(ALLOWED_FILE_EXCLUSIONS[path].engines)}), ${methodsOf(path)} test methods`),
    '',
    '**Infrastructure each engine replaces with its own**, not a gap: the host\'s wiring on EF Core, and the suite\'s web factory and fixture.',
    '',
    ...wiring.map((path) => `- \`${path}\` (${engines(ALLOWED_EXCLUSIONS[path].engines)})`),
    ...replaced.map(([path, a]) => `- \`${suitePath(path)}\` (${engines(a.engines)})`),
    '',
  );

  return lines.join('\n');
}

/** The EF Core suite's sources, paths from the root, as the gate lists them. */
export function suiteSources(root) {
  return readdirSync(join(root, SUITE_DIR), { recursive: true }).map((f) => `${SUITE_DIR}/${String(f).replaceAll('\\', '/')}`)
    .filter((f) => f.endsWith('.cs') && !/\/(bin|obj)\//.test(f));
}

/** The page as the lists say it, for the repository at <paramref name="root" />. */
export function expectedPage(root) {
  const read = (path) => (existsSync(join(root, path)) ? readFileSync(join(root, path), 'utf-8') : null);
  return coveragePage(read, suiteSources(root));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const expected = expectedPage(root);
  const target = join(root, COVERAGE_PAGE);
  if (process.argv.includes('--check')) {
    const actual = existsSync(target) ? readFileSync(target, 'utf-8').replaceAll('\r\n', '\n') : null;
    if (actual !== expected) {
      console.error(`${COVERAGE_PAGE} differs from what engine-projects.mjs and engine-suites.mjs say: run node scripts/engine-coverage.mjs`);
      process.exit(1);
    }
  } else {
    writeFileSync(target, expected);
    console.log(`wrote ${COVERAGE_PAGE}`);
  }
}
