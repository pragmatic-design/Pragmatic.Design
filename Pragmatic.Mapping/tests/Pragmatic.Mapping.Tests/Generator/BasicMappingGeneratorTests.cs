    [Fact]
    public void MapFrom_PositionalRecord_ConstructsViaPrimaryConstructor()
    {
        // A positional record has no parameterless ctor; the old object-initializer form
        // (new OrderLineDto { ... }) failed to compile (CS1729). FromEntity must call the primary ctor.
        var source = """
                     using Pragmatic.Mapping.Attributes;

                     namespace TestApp.Entities
                     {
                         public class OrderLine
                         {
                             public string Sku { get; set; } = "";
                             public int Quantity { get; set; }
                         }
                     }

                     namespace TestApp.Dtos
                     {
                         [MapFrom<TestApp.Entities.OrderLine>]
                         public partial record OrderLineDto(string Sku, int Quantity);
                     }
                     """;

        var result = RunGenerator(source);

        HasCompilationErrors(result).Should().BeFalse(
            string.Join(", ", GetCompilationErrors(result).Select(d => d.ToString())));

        var mapping = GetGeneratedSourcesAsDictionary(result)
            .First(kv => kv.Key.EndsWith("OrderLineDto.Mapping.g.cs")).Value;
        mapping.Should().Contain("new OrderLineDto(ctx.Sku, ctx.Quantity)")
            .And.NotContain("new OrderLineDto()");
    }

    /// <summary>
    ///     A DTO property named after a foreign key that <c>[Relation.*]</c> generates.
    /// </summary>
    /// <remarks>
    ///     The foreign key does not exist on the symbol during this pass, so the mapping resolved it
    ///     to nothing: PRAG0303, and the column dropped from the projection <i>silently</i> — the
    ///     client received an empty Guid. A consumer only noticed by reading the payload.
    /// </remarks>
    [Fact]
    public void MapFrom_RelationForeignKey_IsMappedNotDropped()
    {
        var source = """
                     using Pragmatic.Mapping.Attributes;
                     using Pragmatic.Persistence.Entity;

                     namespace TestApp.Entities
                     {
                         [Entity]
                         public partial class Supplier { public string Name { get; set; } = ""; }

                         [Entity]
                         [Relation.ManyToOne<Supplier>]
                         public partial class Assignment
                         {
                             public decimal Amount { get; set; }
                         }
                     }

                     namespace TestApp.Dtos
                     {
                         [MapFrom<TestApp.Entities.Assignment>]
                         public partial class AssignmentDto
                         {
                             public System.Guid SupplierId { get; set; }
                             public decimal Amount { get; set; }
                         }
                     }
                     """;

        var result = RunGenerator(source);

        GetGeneratorDiagnostics(result).Should().NotContain(d => d.Id == "PRAG0303",
            "SupplierId is generated by the relation, so it is not an unmapped property");

        var mapping = GetGeneratedSourcesAsDictionary(result)
            .First(kv => kv.Key.EndsWith("AssignmentDto.Mapping.g.cs")).Value;
        mapping.Should().Contain("SupplierId", "the foreign key belongs in the mapping, not dropped from it");
    }

    /// <summary>
    ///     A projection that flattens through a navigation <c>[Relation.*]</c> generates.
    /// </summary>
    /// <remarks>
    ///     The companion of the foreign-key case above: the navigation is generated too, so unless it is
    ///     predicted <c>WorkItem.Description</c> fails on its first segment and the property is dropped
    ///     without a diagnostic. Two things have to be true for this to work — the navigation has to be
    ///     predicted at all, and the path resolver has to be allowed to walk <i>through</i> it, although
    ///     it is generated.
    /// </remarks>
    [Fact]
    public void Projection_FlattensThroughGeneratedNavigation()
    {
        var source = """
                     using Pragmatic.Mapping.Attributes;
                     using Pragmatic.Persistence.Entity;

                     namespace TestApp.Entities
                     {
                         [Entity]
                         public partial class Worksite { public string Address { get; set; } = ""; }

                         [Entity]
                         [Relation.ManyToOne<Worksite>]
                         public partial class WorkItem { public string Description { get; set; } = ""; }

                         [Entity]
                         [Relation.ManyToOne<WorkItem>]
                         public partial class Assignment { public decimal Amount { get; set; } }
                     }

                     namespace TestApp.Dtos
                     {
                         [MapFrom<TestApp.Entities.Assignment>]
                         [GenerateProjection]
                         public partial class MyAssignmentDto
                         {
                             [MapProperty("WorkItem.Description")]
                             public string WorkItemDescription { get; set; } = "";

                             [MapProperty("WorkItem.Worksite.Address")]
                             public string WorksiteAddress { get; set; } = "";

                             public decimal Amount { get; set; }
                         }
                     }
                     """;

        var result = RunGenerator(source);

        // Deliberately not asserting on compilation: this harness runs the Mapping generator alone,
        // so the navigation the path walks through is never emitted and the generated projection
        // cannot compile here (CS1061 on WorkItem). What this test can prove is that the path
        // resolved instead of being dropped; that the result compiles and runs is proved by the
        // Showcase, where the whole generator runs against a real database.

        var mapping = GetGeneratedSourcesAsDictionary(result)
            .First(kv => kv.Key.EndsWith("MyAssignmentDto.Mapping.g.cs")).Value;

        mapping.Should().Contain("WorkItem.Description",
            "the first segment is a generated navigation, and the path has to walk into it");
        mapping.Should().Contain("WorkItem.Worksite.Address",
            "two generated navigations in one path: the resolver has to keep going past the first");
    }

    [Fact]
    public void MapTo_GeneratesWriteSideHooks()
    {
        var source = """
                     using Pragmatic.Mapping.Attributes;

                     namespace TestApp.Entities
                     {
                         public class Order { public string Description { get; set; } = ""; }
                     }
                     namespace TestApp.Dtos
                     {
                         [MapTo<TestApp.Entities.Order>]
                         public partial record UpdateOrderDto { public string Description { get; init; } = ""; }
                     }
                     """;

        var result = RunGenerator(source);
        HasCompilationErrors(result).Should().BeFalse(
            string.Join(", ", GetCompilationErrors(result).Select(d => d.ToString())));

        var mapping = GetGeneratedSourcesAsDictionary(result)
            .First(kv => kv.Key.EndsWith("UpdateOrderDto.Mapping.g.cs")).Value;

        // Write-side hooks, symmetric to the read-side BeforeMapping/CustomizeMapping.
        mapping.Should().Contain("BeforeToEntity(ref customResult);")
            .And.Contain("CustomizeToEntity(entity);")
            .And.Contain("CustomizeApplyTo(entity);")
            .And.Contain("partial void BeforeToEntity(ref global::TestApp.Entities.Order? result);")
            .And.Contain("partial void CustomizeToEntity(global::TestApp.Entities.Order entity);")
            .And.Contain("partial void CustomizeApplyTo(global::TestApp.Entities.Order entity);");
    }

