    // =========================================================================
    // [MapTo] + [Mutation] Integration Tests
    // =========================================================================

    [Fact]
    public void MapTo_WithPatchAttribute_SkipsApplyToGeneration()
    {
        var source = """
                     using Pragmatic.Mapping.Attributes;
                     using Pragmatic.Persistence.Patch;

                     namespace TestApp.Entities
                     {
                         public class Product
                         {
                             public int Id { get; set; }
                             public string Name { get; set; } = "";
                             public decimal Price { get; set; }
                         }
                     }

                     namespace TestApp.Dtos
                     {
                         // DTO has both [MapTo] and [Patch] - ApplyTo should NOT be generated by Mapping
                         // because Patch generator will handle update semantics
                         [MapTo<TestApp.Entities.Product>]
                         [Patch<TestApp.Entities.Product>]
                         public partial record UpdateProductDto
                         {
                             public string Name { get; init; } = "";
                             public decimal Price { get; init; }
                         }
                     }
                     """;

        var result = RunGenerator(source);

        HasCompilationErrors(result).Should().BeFalse(
            string.Join(", ", GetCompilationErrors(result).Select(d => d.ToString())));

        var mainSource = GetGeneratedSource(result, "UpdateProductDto.Mapping");
        mainSource.Should().NotBeNull();

        // Should have ToEntity (from [MapTo])
        mainSource.Should().Contain("ToEntity");

        // Should NOT have ApplyTo (because [Mutation] is present - Mutation generator handles this)
        mainSource.Should().NotContain("ApplyTo");
    }

