using Pragmatic.Actions.Mutation;
using Pragmatic.Endpoints;
using Pragmatic.Endpoints.Attributes;
using Pragmatic.Persistence.Entity;
using Conformance.Sales.Dtos;
using Conformance.Sales.Entities;

namespace Conformance.Sales.Mutations;

/// <summary>
///     Creates an order with its lines, in one go.
/// </summary>
/// <remarks>
///     <para>
///         Demonstrates: <c>ToEntity()</c> builds the whole graph without touching the database, because
///         on creation there is nothing to load.
///     </para>
///     <para>
///         ⚠️ <c>[AllowAnonymous]</c> because authorization is a cell of the matrix <b>of its own</b>, not
///         an accessory of this one. Putting it here would make every test depend on a permission and
///         would not prove authorization any better than a dedicated test.
///     </para>
/// </remarks>
[Mutation(Mode = MutationMode.Create)]
[AllowAnonymous]
[Endpoint(HttpVerb.Post, "api/orders")]
[ReturnsDto<OrderDto>]
public partial class CreateOrderMutation : Mutation<Order>
{
    public required string Reference { get; init; }

    /// <summary>
    ///     The initial lines. The name is that of the navigation generated by
    ///     <c>[Relation.OneToMany&lt;OrderLine&gt;]</c>: naming it differently would be <c>PRAG0439</c>.
    /// </summary>
    public required List<WriteOrderLineMutation> Lines { get; init; }
}
