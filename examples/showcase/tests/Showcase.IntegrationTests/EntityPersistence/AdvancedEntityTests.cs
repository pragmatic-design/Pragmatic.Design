    // =========================================================================
    // GenerateProjection: InvoiceSummaryDto has formatted fields
    // =========================================================================

    [Fact]
    public async Task MapFromEntity_Invoice_HasFormattedFields()
    {
        var reservationId = await CreateAndConfirmReservationAsync();

        // Get invoice ID from search
        var invoiceSearch = await GetAsync<JsonElement>(
            $"/api/invoices/search?reservationId={reservationId}");
        var items = invoiceSearch.GetProperty("items");
        items.GetArrayLength().Should().BeGreaterOrEqualTo(1);
        var invoiceId = items[0].GetProperty("id").GetGuid();

        // Use GetInvoice endpoint (calls FromEntity() — supports MapProperty Format + MapConverter)
        var invoice = await GetAsync<JsonElement>($"/api/invoices/{invoiceId}");

        // IssuedDate is [MapProperty(Format = "yyyy-MM-dd")] — formatted date via FromEntity()
        invoice.TryGetProperty("issuedDate", out var issuedDate).Should().BeTrue(
            "IssuedDate should be present (MapProperty with Format)");
        issuedDate.GetString().Should().MatchRegex(@"\d{4}-\d{2}-\d{2}",
            "IssuedDate should be formatted as yyyy-MM-dd");

        // TotalFormatted is [MapConverter<MoneyToStringConverter>]
        invoice.TryGetProperty("totalFormatted", out var totalFormatted).Should().BeTrue(
            "TotalFormatted should be present (MapConverter)");
        totalFormatted.GetString().Should().NotBeNullOrWhiteSpace(
            "TotalFormatted should be a formatted money string");
    }

    /// <summary>
    ///     The search is a query, and its projection carries the formatted and converted members
    ///     exactly as <c>FromEntity</c> computes them: it answered <c>""</c> for both.
    /// </summary>
    [Fact]
    public async Task SearchInvoices_CarriesTheFormattedFields_AsTheInMemoryMappingDoes()
    {
        var reservationId = await CreateAndConfirmReservationAsync();

        var searched = (await GetAsync<JsonElement>($"/api/invoices/search?reservationId={reservationId}"))
            .GetProperty("items")[0];
        var read = await GetAsync<JsonElement>($"/api/invoices/{searched.GetProperty("id").GetGuid()}");

        searched.GetProperty("issuedDate").GetString().Should().MatchRegex(@"^\d{4}-\d{2}-\d{2}$");
        searched.GetProperty("issuedDate").GetString().Should().Be(read.GetProperty("issuedDate").GetString());
        searched.GetProperty("totalFormatted").GetString().Should().NotBeNullOrWhiteSpace();
        searched.GetProperty("totalFormatted").GetString().Should().Be(read.GetProperty("totalFormatted").GetString());
    }

