    // =========================================================================
    // Soft Delete Cascade: delete Property → RoomTypes excluded from search
    // =========================================================================

    [Fact]
    public async Task SoftDeleteCascade_DeleteProperty_RoomTypesExcludedFromSearch()
    {
        // Create property + room type
        var property = await CreatePropertyAsync();
        var propertyId = property.GetProperty("id").GetGuid();

        var rtBody = new
        {
            propertyId,
            name = $"CascadeRT-{Guid.NewGuid():N}"[..15],
            code = "CRT",
            baseRate = 100m,
            totalRooms = 5
        };
        var roomType = await PostAsync<JsonElement>("/api/room-types", rtBody);
        var roomTypeId = roomType.GetProperty("id").GetGuid();

        // Verify room type visible in search before delete
        var beforeSearch = await GetAsync<JsonElement>($"/api/room-types/search?propertyId={propertyId}");
        ContainsId(beforeSearch, roomTypeId).Should().BeTrue("RoomType should be visible before property deletion");

        // Delete property (cascade soft delete)
        var deleteResponse = await DeleteAsync($"/api/properties/{propertyId}");
        deleteResponse.StatusCode.Should().Be(HttpStatusCode.NoContent, "a delete answers 204 and no body");

        // RoomType should be excluded from search (soft-delete cascaded)
        var afterSearch = await GetAsync<JsonElement>($"/api/room-types/search?propertyId={propertyId}&pageSize=50");
        ContainsId(afterSearch, roomTypeId).Should().BeFalse(
            "RoomType should be excluded by soft-delete cascade when parent Property is deleted");
    }

    [Fact]
    public async Task SoftDeleteCascade_DeleteProperty_CancellationPolicyExcluded()
    {
        // Create property + cancellation policy
        var property = await CreatePropertyAsync();
        var propertyId = property.GetProperty("id").GetGuid();

        var policyBody = new
        {
            propertyId,
            name = "Cascade Policy",
            hoursBeforeCheckIn = 48,
            penaltyPercentage = 25.0m,
            isDefault = true
        };
        var policyResponse = await PostAsync("/api/cancellation-policies", policyBody);
        policyResponse.StatusCode.Should().Be(HttpStatusCode.Created);

        // Delete property (cascade)
        var deleteResponse = await DeleteAsync($"/api/properties/{propertyId}");
        deleteResponse.StatusCode.Should().Be(HttpStatusCode.NoContent, "a delete answers 204 and no body");

        // Property is deleted → cascaded entities should also be soft-deleted
        // Verify by restoring property and checking that child entities are still deleted
        var restoreResponse = await PostAsync($"/api/properties/{propertyId}/restore", new { });
        restoreResponse.StatusCode.Should().Be(HttpStatusCode.NoContent);

        // After restoring only the property, the cascaded children remain soft-deleted
        // The parent is visible again but children are still deleted
        var restored = await GetRawAsync($"/api/properties/{propertyId}");
        restored.StatusCode.Should().Be(HttpStatusCode.OK,
            "Property should be restored: a soft-deleted row is filtered out of the read");
    }

