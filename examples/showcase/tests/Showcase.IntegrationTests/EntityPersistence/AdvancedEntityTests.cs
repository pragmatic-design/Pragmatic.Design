    // GeneratedValue + ComputedDefault: Invoice.InvoiceNumber auto-generated
    // =========================================================================

    [Fact]
    public async Task GeneratedValue_Invoice_HasAutoGeneratedInvoiceNumber()
    {
        var reservationId = await CreateAndConfirmReservationAsync();

        // Get invoice created by domain event
        var invoiceSearch = await GetAsync<JsonElement>(
            $"/api/invoices/search?reservationId={reservationId}");
        var items = invoiceSearch.GetProperty("items");
        items.GetArrayLength().Should().BeGreaterOrEqualTo(1, "Invoice should be auto-created on confirmation");

        var invoice = items[0];
        var invoiceNumber = invoice.GetProperty("invoiceNumber").GetString();

        // The declared format is INV-{YYYY}{MM}-{SEQ:5}, so the whole shape is asserted rather than
        // the prefix. StartWith("INV-") was true of a number hand-written by CreateInvoiceWithFees
        // too, in a different format and with no sequence — an assertion that could not tell the
        // generator from a workaround around it.
        invoiceNumber.Should().MatchRegex(@"^INV-\d{6}-\d{5}$",
            "the format on [GeneratedValue] is INV-{YYYY}{MM}-{SEQ:5}, and the sequence is five digits");
    }

    // =========================================================================
    // MapProperty (navigation flattening): ReservationSummaryDto
    // =========================================================================

    [Fact]
    public async Task MapProperty_ReservationDto_FlattensNavigationProperties()
    {
        // Create full reservation with guest + property
        var guestBody = new
        {
            firstName = "MapProp",
            lastName = "Test",
            email = $"mapprop.{Guid.NewGuid():N}@test.com"
        };
        var guest = await PostAsync<JsonElement>("/api/guests", guestBody);
        var guestId = guest.GetProperty("id").GetGuid();

        var property = await CreatePropertyAsync("MapProp Hotel");
        var propertyId = property.GetProperty("id").GetGuid();

        var rtBody = new
        {
            propertyId,
            name = "MP Room",
            code = "MPR",
            baseRate = 100m,
            totalRooms = 5
        };
        var roomType = await PostAsync<JsonElement>("/api/room-types", rtBody);
        var roomTypeId = roomType.GetProperty("id").GetGuid();

        var reservationBody = new
        {
            request = new
            {
                guestId,
                propertyId,
                roomTypeId,
                checkIn = DateTimeOffset.UtcNow.AddDays(7).ToString("O"),
                checkOut = DateTimeOffset.UtcNow.AddDays(10).ToString("O"),
                numberOfGuests = 2
            }
        };
        var resResponse = await PostAsync("/api/reservations?api-version=1.0", reservationBody);
        resResponse.StatusCode.Should().Be(HttpStatusCode.Created);
        var reservationId = await resResponse.Content.ReadFromJsonAsync<Guid>(JsonOptions);

        // Get reservation DTO — should have flattened navigation properties
        var dto = await GetAsync<JsonElement>($"/api/reservations/{reservationId}");

        // [MapProperty("Guest.FirstName")] → GuestFirstName
        dto.GetProperty("guestFirstName").GetString().Should().Be("MapProp",
            "GuestFirstName should be flattened from Guest.FirstName via [MapProperty]");

        // [MapProperty("Guest.LastName")] → GuestLastName
        dto.GetProperty("guestLastName").GetString().Should().Be("Test",
            "GuestLastName should be flattened from Guest.LastName via [MapProperty]");

        // [MapProperty("Property.Name")] → PropertyName
        dto.GetProperty("propertyName").GetString().Should().Contain("MapProp",
            "PropertyName should be flattened from Property.Name via [MapProperty]");
    }

