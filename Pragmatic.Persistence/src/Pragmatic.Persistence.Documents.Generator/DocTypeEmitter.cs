using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Pragmatic.Persistence.Documents.Generator;

/// <summary>
///     The other half of a [Document] or [Embedded] partial class: <c>IDocumentEntity&lt;T&gt;</c> (or <c>IEmbeddedDocument&lt;T&gt;</c>) implemented
///     explicitly, so the type's own members stay the developer's: the fields written in order (<c>_id</c> first), the document read field by
///     field comparing the UTF-8 names, the key and the version.
/// </summary>
internal static class DocTypeEmitter
{
    private const string Runtime = "global::Pragmatic.Persistence.Documents";
    private const string Bson = "global::Pragmatic.Persistence.Documents.Mongo.Bson";

    /// <summary>The type's partial, or null (reported) when the type cannot take one: not partial, nested, generic.</summary>
    public static string? Emit(DocModel model, List<Diagnostic> diagnostics, List<string>? families = null)
    {
        var type = model.Type;
        var where = type.Locations.FirstOrDefault() ?? Location.None;
        var partial = type.DeclaringSyntaxReferences.Select(r => r.GetSyntax()).OfType<TypeDeclarationSyntax>().Any(d => d.Modifiers.Any(m => m.ValueText == "partial"));
        if (!partial || type.ContainingType is not null || type.IsGenericType || type.TypeKind != TypeKind.Class)
        {
            diagnostics.Add(Diagnostic.Create(DocDiagnostics.NotPartial, where, type.Name + (type.ContainingType is not null ? " (a top-level class: nested types are not supported)" : type.IsGenericType ? " (a non-generic class)" : "")));
            return null;
        }

        var name = model.FullName;
        var contract = model.IsEmbedded ? $"{Runtime}.IEmbeddedDocument<{name}>" : $"{Runtime}.IDocumentEntity<{name}>";
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/> Pragmatic.Persistence.Documents: the document reader and writer of " + type.Name + ".");
        source.AppendLine("#nullable enable");
        var ns = type.ContainingNamespace.IsGlobalNamespace ? null : type.ContainingNamespace.ToDisplayString();
        if (ns is not null)
            source.AppendLine($"namespace {ns};");
        source.AppendLine();
        source.AppendLine($"partial class {type.Name} : {contract}");
        source.AppendLine("{");
        if (!model.IsEmbedded)
        {
            source.AppendLine($"    static string {contract}.Collection => {Literal(model.Collection!)};");
            source.AppendLine();
        }

        // The fields in order, the key first: a document's _id is its first field.
        source.AppendLine($"    static void {contract}.WriteFields({Bson}.BsonWriter w, {name} e)");
        source.AppendLine("    {");
        foreach (var field in model.Fields.OrderBy(f => f.Name == "_id" ? 0 : 1))
            source.AppendLine("        " + WriteField(field, "e." + field.Property.Name) + ";");
        source.AppendLine("    }");
        source.AppendLine();

        source.AppendLine($"    static {name} {contract}.ReadDocument(global::System.ReadOnlySpan<byte> document)");
        source.AppendLine("    {");
        source.AppendLine($"        var r = new {Bson}.BsonReader(document);");
        source.AppendLine($"        var e = new {name}();");
        source.AppendLine("        while (r.ReadElement(out var type, out var name))");
        source.AppendLine("        {");
        source.AppendLine($"            if (type == {Bson}.BsonType.Null)");
        source.AppendLine("            {");
        source.AppendLine("                r.Skip(); // a null leaves the property at its default");
        source.AppendLine("                continue;");
        source.AppendLine("            }");
        source.AppendLine();
        var first = true;
        foreach (var field in model.Fields)
        {
            source.AppendLine($"            {(first ? "if" : "else if")} (global::System.MemoryExtensions.SequenceEqual(name, {Literal(field.Name)}u8))");
            source.AppendLine($"                e.{field.Property.Name} = {ReadField(field)};");
            first = false;
        }

        source.AppendLine(first ? "            r.Skip();" : "            else");
        if (!first)
            source.AppendLine("                r.Skip(); // a field the model does not have");
        source.AppendLine("        }");
        source.AppendLine();
        source.AppendLine("        return e;");
        source.AppendLine("    }");

        if (!model.IsEmbedded)
        {
            var key = model.Key!;
            source.AppendLine();
            source.AppendLine($"    static void {contract}.WriteKey({Bson}.BsonWriter w, string name, {name} e) => {WriteField(key, "e." + key.Property.Name, "name")};");
            source.AppendLine();
            source.AppendLine($"    static bool {contract}.Versioned => {(model.Version is null ? "false" : "true")};");
            source.AppendLine();
            source.AppendLine($"    static long {contract}.GetVersion({name} e) => {(model.Version is null ? "0" : "unchecked((long)e." + model.Version.Property.Name + ")")};");
            source.AppendLine();
            source.AppendLine($"    static void {contract}.SetVersion({name} e, long version) {{ {(model.Version is null ? "" : $"e.{model.Version.Property.Name} = unchecked(({model.Version.ScalarName})version); ")}}}");
            if (families is { Count: > 0 })
            {
                // A Pragmatic entity's filter families (DocFamiliesEmitter), applied to every read of it.
                source.AppendLine();
                source.AppendLine($"    private static readonly {Runtime}.DocFamily[] __documentFamilies =");
                source.AppendLine("    [");
                foreach (var family in families)
                    source.AppendLine("        " + family + ",");
                source.AppendLine("    ];");
                source.AppendLine();
                source.AppendLine($"    static {Runtime}.DocFamily[] {contract}.Families => __documentFamilies;");
            }
        }

        DocJsonEmitter.Append(source, model, contract);
        source.AppendLine("}");
        return source.ToString();
    }

    /// <summary>The statement that writes one field's value under its name (or under <paramref name="nameExpression" />, a C# expression).</summary>
    public static string WriteField(DocField field, string value, string? nameExpression = null)
    {
        var name = nameExpression ?? Literal(field.Name);
        switch (field.Kind)
        {
            case DocKind.Embedded:
                return $"{Runtime}.DocMapping.WriteEmbedded<{field.Embedded!.ToDisplayString(DocModel.Qualified)}>(w, {name}, {value})";
            case DocKind.List when field.ElementKind == DocKind.Embedded:
                return $"{Runtime}.DocMapping.WriteEmbeddedList<{field.Embedded!.ToDisplayString(DocModel.Qualified)}>(w, {name}, {value})";
            case DocKind.List:
                return $"{Runtime}.DocMapping.WriteList<{field.Element!.ToDisplayString(DocModel.Qualified)}>(w, {name}, {value}, {Runtime}.DocValues.Write)";
            case DocKind.Enum:
                return field.Nullable
                    ? $"{Runtime}.DocValues.Write(w, {name}, {value} is {{ }} v ? (int?)(int)v : null)"
                    : $"w.Write({name}, (int){value})";
            case DocKind.DateTime:
                return field.Nullable ? $"{Runtime}.DocMapping.Write(w, {name}, {value})" : $"{Runtime}.DocValues.Write(w, {name}, {value})";
            case DocKind.UInt64:
                return $"{Runtime}.DocValues.Write(w, {name}, unchecked((long){value}))";
            default:
                return $"{Runtime}.DocValues.Write(w, {name}, {value})";
        }
    }

    private static string ReadField(DocField field)
    {
        switch (field.Kind)
        {
            case DocKind.Embedded:
                return $"{Runtime}.DocMapping.ReadEmbedded<{field.Embedded!.ToDisplayString(DocModel.Qualified)}>(r.ReadDocument())";
            case DocKind.List when field.ElementKind == DocKind.Embedded:
                return $"{Runtime}.DocMapping.ReadEmbeddedList<{field.Embedded!.ToDisplayString(DocModel.Qualified)}>(r.ReadDocument())";
            case DocKind.List:
                return $"{Runtime}.DocMapping.ReadList<{field.Element!.ToDisplayString(DocModel.Qualified)}>(r.ReadDocument(), static (ref {Bson}.BsonReader x) => {ReadScalar(field.ElementKind, "x", field.Element!.ToDisplayString(DocModel.Qualified))})";
            default:
                return ReadScalar(field.Kind, "r", field.ScalarName);
        }
    }

    private static string ReadScalar(DocKind kind, string reader, string typeName) => kind switch
    {
        DocKind.String => $"{reader}.ReadString()",
        DocKind.Int32 => $"{Runtime}.DocMapping.ReadInt32(ref {reader})",
        DocKind.Int64 => $"{Runtime}.DocMapping.ReadInt64(ref {reader})",
        DocKind.UInt64 => $"unchecked((ulong){Runtime}.DocMapping.ReadInt64(ref {reader}))",
        DocKind.Double => $"{Runtime}.DocMapping.ReadDouble(ref {reader})",
        DocKind.Decimal => $"{Runtime}.DocMapping.ReadDecimal(ref {reader})",
        DocKind.Boolean => $"{reader}.ReadBoolean()",
        DocKind.Guid => $"{reader}.ReadGuid()",
        DocKind.DateTimeOffset => $"{reader}.ReadDateTime()",
        DocKind.DateTime => $"{Runtime}.DocMapping.ReadDateTime(ref {reader})",
        DocKind.Enum => $"({typeName}){Runtime}.DocMapping.ReadInt32(ref {reader})",
        _ => $"default! /* {kind} */",
    };

    public static string Literal(string text) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(text, quote: true);
}
