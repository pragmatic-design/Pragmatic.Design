using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Pragmatic.Persistence.Sql.Generator;

/// <summary>
///     The persistence of each boundary an engine serves, registered as Pragmatic registers a boundary's (<c>RepositoryRegistrationTemplate</c>,
///     <c>BoundaryKeyedServices</c>): the unit of work keyed by <c>typeof(TBoundary)</c>, its session with it, and each entity's
///     <c>IRepository&lt;T&gt;</c> and <c>IReadRepository&lt;T&gt;</c> unkeyed (an entity has one boundary). The session is the host's to open (its
///     connection, its database); the filters are built here from the services Pragmatic registers, and handed to it. One method per boundary,
///     <c>Add{Boundary}Persistence</c>: two boundaries on two engines in one host are two calls. Ported, this is the engine's branch of the template.
/// </summary>
internal sealed class PragmaticRegistration(string session, string filters, string bridgeFilters, string unitOfWork, string phase, string repository)
{
    private const string ServiceCollection = "global::Microsoft.Extensions.DependencyInjection.IServiceCollection";

    public static readonly PragmaticRegistration Sql = new(
        "global::Pragmatic.Persistence.Sql.SqlSession", "global::Pragmatic.Persistence.Sql.ISqlFilters", "global::Pragmatic.Persistence.Sql.Pragmatic.PragmaticSqlFilters",
        "global::Pragmatic.Persistence.Sql.Pragmatic.SqlUnitOfWork", "global::Pragmatic.Persistence.Sql.Pragmatic.ISqlSavePhase", "SqlRepository");

    public static readonly PragmaticRegistration Documents = new(
        "global::Pragmatic.Persistence.Documents.DocSession", "global::Pragmatic.Persistence.Documents.IDocFilters", "global::Pragmatic.Persistence.Documents.Pragmatic.PragmaticDocFilters",
        "global::Pragmatic.Persistence.Documents.Pragmatic.DocUnitOfWork", "global::Pragmatic.Persistence.Documents.Pragmatic.IDocSavePhase", "DocRepository");

    /// <summary>
    ///     One source per boundary of <paramref name="entities" /> (the ones the engine serves); none without the dependency injection abstractions
    ///     or the engine's unit of work in the compilation. An entity without a boundary is not registered: it has no key.
    /// </summary>
    public List<(string Hint, string Source)> For(Compilation compilation, IEnumerable<INamedTypeSymbol> entities)
    {
        var sources = new List<(string, string)>();
        if (compilation.GetTypeByMetadataName("Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions") is null
            || compilation.GetTypeByMetadataName(unitOfWork.Substring("global::".Length)) is null)
            return sources;
        foreach (var group in entities.Select(e => (Entity: e, Boundary: PragmaticPermissions.BoundaryOf(e))).Where(p => p.Boundary is INamedTypeSymbol)
                     .GroupBy(p => p.Boundary!, SymbolEqualityComparer.Default).OrderBy(g => g.Key!.ToDisplayString(), System.StringComparer.Ordinal))
        {
            var boundary = (INamedTypeSymbol)group.Key!;
            if (!SymbolEqualityComparer.Default.Equals(boundary.ContainingAssembly, compilation.Assembly))
                continue; // a boundary of a referenced assembly registers there
            sources.Add(($"{boundary.ToDisplayString().Replace('.', '_')}.Persistence.g.cs",
                Text(boundary, group.Select(p => p.Entity).OrderBy(e => e.ToDisplayString(), System.StringComparer.Ordinal).ToList())));
        }

        return sources;
    }

    private string Text(INamedTypeSymbol boundary, List<INamedTypeSymbol> entities)
    {
        var key = $"typeof({boundary.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)})";
        var text = new StringBuilder();
        text.AppendLine("// <auto-generated/>");
        text.AppendLine("#nullable enable");
        if (!boundary.ContainingNamespace.IsGlobalNamespace)
            text.AppendLine($"namespace {boundary.ContainingNamespace.ToDisplayString()};");
        text.AppendLine();
        text.AppendLine($"/// <summary>The persistence of {boundary.Name}: its unit of work keyed by its type, its entities' repositories.</summary>");
        text.AppendLine($"public static class {boundary.Name}Persistence");
        text.AppendLine("{");
        text.AppendLine("    /// <summary>");
        text.AppendLine($"    ///     Registers {boundary.Name}'s unit of work (keyed by <c>typeof({boundary.Name})</c>) and its entities' repositories. <paramref name=\"session\" />");
        text.AppendLine("    ///     opens the boundary's session with the filters built from the request's services.");
        text.AppendLine("    /// </summary>");
        text.AppendLine($"    public static {ServiceCollection} Add{boundary.Name}Persistence(this {ServiceCollection} services, global::System.Func<global::System.IServiceProvider, {filters}, {session}> session)");
        text.AppendLine("    {");
        text.AppendLine($"        global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddKeyedScoped<{session}>(services, {key}, (sp, _) => session(sp, new {bridgeFilters}(");
        text.AppendLine("            Get<global::Pragmatic.Identity.ICurrentUser>(sp), Get<global::Pragmatic.MultiTenancy.ITenantContext>(sp), Get<global::Pragmatic.Authorization.IUserScopeResolver>(sp),");
        text.AppendLine("            Get<global::Pragmatic.Persistence.Query.Filters.IQueryFilterToggle>(sp), Get<global::Pragmatic.Persistence.Query.Filters.QueryFilterOptions>(sp), Get<global::System.TimeProvider>(sp),");
        text.AppendLine("            All<global::Pragmatic.Persistence.Scopes.DataScopeRule>(sp))));");
        // ASSUMPTION: requireTenant false, as a unit of work built without options; the repo's tenant interceptor option is a porting item.
        text.AppendLine($"        global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddKeyedScoped<{unitOfWork}>(services, {key}, (sp, k) => new {unitOfWork}(");
        text.AppendLine($"            global::Microsoft.Extensions.DependencyInjection.ServiceProviderKeyedServiceExtensions.GetRequiredKeyedService<{session}>(sp, k), Get<global::System.TimeProvider>(sp),");
        text.AppendLine("            Get<global::Pragmatic.Identity.ICurrentUser>(sp), Get<global::Pragmatic.MultiTenancy.ITenantContext>(sp), false, All<global::Pragmatic.Persistence.Lifecycle.IGeneratedValueBinding>(sp),");
        text.AppendLine($"            Get<global::Pragmatic.Events.IDomainEventDispatcher>(sp), All<{phase}>(sp), All<global::Pragmatic.Persistence.Scopes.DataScopeRule>(sp)));");
        text.AppendLine($"        global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddKeyedScoped<global::Pragmatic.Persistence.Repository.IUnitOfWork>(services, {key},");
        text.AppendLine($"            (sp, k) => global::Microsoft.Extensions.DependencyInjection.ServiceProviderKeyedServiceExtensions.GetRequiredKeyedService<{unitOfWork}>(sp, k));");
        foreach (var entity in entities)
        {
            var type = entity.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            text.AppendLine($"        global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddScoped<global::Pragmatic.Persistence.Repository.IRepository<{type}>>(services,");
            text.AppendLine($"            sp => new {type}.{repository}(global::Microsoft.Extensions.DependencyInjection.ServiceProviderKeyedServiceExtensions.GetRequiredKeyedService<{unitOfWork}>(sp, {key})));");
            text.AppendLine($"        global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddScoped<global::Pragmatic.Persistence.Repository.IReadRepository<{type}>>(services,");
            text.AppendLine($"            sp => global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<global::Pragmatic.Persistence.Repository.IRepository<{type}>>(sp));");
        }

        text.AppendLine("        return services;");
        text.AppendLine("    }");
        text.AppendLine();
        text.AppendLine("    private static T? Get<T>(global::System.IServiceProvider sp) where T : class => (T?)sp.GetService(typeof(T));");
        text.AppendLine();
        text.AppendLine("    private static global::System.Collections.Generic.IEnumerable<T> All<T>(global::System.IServiceProvider sp)");
        text.AppendLine("        => global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetServices<T>(sp);");
        text.AppendLine("}");
        return text.ToString();
    }
}
