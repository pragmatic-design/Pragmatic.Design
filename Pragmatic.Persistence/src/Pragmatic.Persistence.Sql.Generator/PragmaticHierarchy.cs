using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Pragmatic.Persistence.Sql.Generator;

/// <summary>
///     Pragmatic's <c>[GenerateHierarchy]</c> on an engine (<c>HierarchyQueryTemplate</c> emits them over a <c>DbContext</c>, with EF Core only):
///     per tree, <c>GetDescendantsBy{Navigation}Async</c> and <c>GetAncestorsBy{Navigation}Async</c>. The engine's runtime walks the parent keys
///     (its <c>keys</c> method, bounded in depth, the start left out, no filter, as Pragmatic's CTE); the rows are then read with a chain on the
///     session, so the caller's filters apply to them. Engine-neutral, linked by the documents generator.
/// </summary>
internal static class PragmaticHierarchy
{
    /// <summary>The entity's hierarchy methods (hint name, text); null when it declares no tree.</summary>
    public static (string Hint, string Source)? For(INamedTypeSymbol entity, string package, string session, string keys)
    {
        var trees = PragmaticRelations.Trees(entity).ToList();
        if (trees.Count == 0)
            return null;
        var type = "global::" + entity.ToDisplayString();
        const string task = "global::System.Threading.Tasks.Task";
        const string ct = "global::System.Threading.CancellationToken ct = default";
        var text = new StringBuilder();
        text.AppendLine($"// <auto-generated/> {package}: the hierarchy queries of a Pragmatic entity ([GenerateHierarchy], PragmaticHierarchy).");
        text.AppendLine("#nullable enable");
        if (!entity.ContainingNamespace.IsGlobalNamespace)
            text.AppendLine($"namespace {entity.ContainingNamespace.ToDisplayString()};");
        text.AppendLine();
        text.AppendLine($"partial class {entity.Name}");
        text.AppendLine("{");
        foreach (var (navigation, foreignKey) in trees)
        {
            foreach (var (name, descendants, start) in new[] { ("GetDescendantsBy" + navigation, true, "rootId"), ("GetAncestorsBy" + navigation, false, "childId") })
            {
                text.AppendLine($"    /// <summary>The {(descendants ? "descendants" : "ancestors")} of the {entity.Name} along {navigation} (the row itself left out), within the session's filters.</summary>");
                text.AppendLine($"    public static async {task}<global::System.Collections.Generic.List<{type}>> {name}Async({session} session, global::System.Guid {start}, {ct})");
                text.AppendLine("    {");
                text.AppendLine($"        var keys = await {keys}<{type}>(session, {PragmaticNames.Literal(foreignKey)}, {start}, descendants: {(descendants ? "true" : "false")}, ct: ct);");
                text.AppendLine($"        return await session.Query<{type}>().Where((e, k) => k.Contains(e.PersistenceId), keys).ToListAsync(ct);");
                text.AppendLine("    }");
                text.AppendLine();
            }
        }

        text.AppendLine("}");
        return ($"{entity.ToDisplayString().Replace('.', '_')}.Hierarchy.g.cs", text.ToString());
    }
}
