using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Pragmatic.Persistence.Sql.Generator;

/// <summary>
///     Pragmatic's <c>IReadRepository&lt;T&gt;</c> for a Pragmatic entity on the Sql engine, as source with chains on <c>SqlQuery&lt;T&gt;</c>: the
///     generator binds and intercepts it like the application's own chains, so every method runs a compiled plan, the entity's filter
///     families included. A specification is read through <c>Matching</c> (its compiled leaves, composed at runtime). <c>Query()</c> is not
///     served (an <c>IQueryable</c> is EF Core's surface, decision of 2026-10-21); a declared query runs through <c>RunAsync</c>, one case per
///     <c>[Query]</c> of the entity (<see cref="PragmaticQuery" />): its filters composed, its sorts ordered, its page taken, its result projected.
/// </summary>
internal static class PragmaticReadRepository
{
    private const string ReadRepository = "Pragmatic.Persistence.Repository.IReadRepository`1";

    /// <summary>True when the compilation has what the repositories are written against: Pragmatic's contracts and the Sql engine's bridge to them.</summary>
    public static bool Applies(Compilation compilation)
        => compilation.GetTypeByMetadataName(ReadRepository) is not null && compilation.GetTypeByMetadataName("Pragmatic.Persistence.Sql.Pragmatic.CompiledSpecification`1") is not null
           && compilation.GetTypeByMetadataName("Pragmatic.Persistence.Sql.Pragmatic.SqlUnitOfWork") is not null;

    /// <summary>The repository nested in <paramref name="entity" />'s partial class (hint name, text); null for an entity that is not an <c>IEntity</c>.</summary>
    public static (string Hint, string Source)? For(INamedTypeSymbol entity, IReadOnlyList<PragmaticQuery> queries)
    {
        if (!System.Linq.Enumerable.Any(entity.AllInterfaces, i => i.ToDisplayString() == "Pragmatic.Persistence.Entity.IEntity"))
            return null;
        var type = "global::" + entity.ToDisplayString();
        const string spec = "global::Pragmatic.Specification.ISpecification";
        const string matching = "Matching(global::Pragmatic.Persistence.Sql.Pragmatic.SqlSpecifications.ToPredicate(spec))";
        var text = new StringBuilder();
        text.AppendLine("// <auto-generated/> Pragmatic.Persistence.Sql: Pragmatic's read repository on the Sql engine (PragmaticReadRepository).");
        text.AppendLine("#nullable enable");
        if (!entity.ContainingNamespace.IsGlobalNamespace)
            text.AppendLine($"namespace {entity.ContainingNamespace.ToDisplayString()};");
        text.AppendLine();
        text.AppendLine($"partial class {entity.Name}");
        text.AppendLine("{");
        text.AppendLine($"    /// <summary>Pragmatic's read repository for {entity.Name} on the Sql engine: every read a compiled plan, the session's filters applied.</summary>");
        text.AppendLine($"    public sealed class SqlReadRepository(global::Pragmatic.Persistence.Sql.SqlSession session) : global::Pragmatic.Persistence.Repository.IReadRepository<{type}>");
        text.AppendLine("    {");
        text.AppendLine($"        public async global::System.Threading.Tasks.Task<{type}?> GetByIdAsync(global::System.Guid id, global::System.Threading.CancellationToken ct = default)");
        text.AppendLine($"            => await session.Query<{type}>().FirstOrDefaultAsync((e, key) => e.PersistenceId == key, id, ct);");
        text.AppendLine();
        text.AppendLine($"        public async global::System.Threading.Tasks.Task<global::System.Collections.Generic.List<{type}>> FindAsync({spec}<{type}> spec, global::System.Threading.CancellationToken ct = default)");
        text.AppendLine($"            => await session.Query<{type}>().{matching}.ToListAsync(ct);");
        text.AppendLine();
        text.AppendLine($"        public async global::System.Threading.Tasks.Task<int> CountAsync({spec}<{type}> spec, global::System.Threading.CancellationToken ct = default)");
        text.AppendLine($"            => await session.Query<{type}>().{matching}.CountAsync(ct);");
        text.AppendLine();
        text.AppendLine($"        public async global::System.Threading.Tasks.Task<bool> ExistsAsync({spec}<{type}> spec, global::System.Threading.CancellationToken ct = default)");
        text.AppendLine($"            => await session.Query<{type}>().{matching}.AnyAsync(ct);");
        text.AppendLine();
        text.AppendLine($"        public async global::System.Threading.Tasks.Task<{type}?> FirstOrDefaultAsync({spec}<{type}> spec, global::System.Threading.CancellationToken ct = default)");
        text.AppendLine($"            => await session.Query<{type}>().{matching}.FirstOrDefaultAsync(ct);");
        text.AppendLine();
        text.AppendLine($"        /// <summary>Not served by the Sql engine: an IQueryable is EF Core's surface. Write the chain on session.Query&lt;{entity.Name}&gt;(), or declare the read.</summary>");
        text.AppendLine($"        public global::System.Linq.IQueryable<{type}> Query()");
        text.AppendLine($"            => throw new global::System.NotSupportedException(\"The Sql engine does not serve IReadRepository<{entity.Name}>.Query(): an IQueryable is EF Core's surface. Write the chain on SqlSession.Query<{entity.Name}>(), or declare the read ([Query], a specification).\");");
        text.AppendLine();
        foreach (var paged in new[] { false, true })
        {
            var result = paged ? "global::Pragmatic.Persistence.Query.Results.PagedResult<TResult>" : "global::System.Collections.Generic.IReadOnlyList<TResult>";
            text.AppendLine($"        public async global::System.Threading.Tasks.Task<{result}> RunAsync<TResult>(global::Pragmatic.Persistence.Query.Interfaces.{(paged ? "IPagedQuery" : "IQuery")}<{type}, TResult> query, global::System.Threading.CancellationToken ct = default) where TResult : class");
            text.AppendLine("        {");
            var cases = queries.Where(q => q.Paged == paged).ToList();
            if (cases.Count > 0)
            {
                text.AppendLine("            switch (query)");
                text.AppendLine("            {");
                foreach (var query in cases)
                    RunCase(text, type, query);
                text.AppendLine("            }");
                text.AppendLine();
            }
            else
                text.AppendLine("            await global::System.Threading.Tasks.Task.CompletedTask; // no declared query of this kind: every call is refused below");
            text.AppendLine($"            throw new global::System.NotSupportedException($\"{{query.GetType().Name}} is not a declared query of {entity.Name} the Sql engine compiled.\");");
            text.AppendLine("        }");
            text.AppendLine();
        }

        text.AppendLine("    }");
        AppendRepository(text, entity, type);
        text.AppendLine("}");
        return ($"{entity.ToDisplayString().Replace('.', '_')}.SqlReadRepository.g.cs", text.ToString());
    }

    /// <summary>
    ///     Pragmatic's <c>IRepository&lt;T&gt;</c> over a unit of work: the reads of the read repository, their rows tracked (the identity map,
    ///     the snapshot a save compares), the writes staged in the unit of work. A row staged without a read carries the check the save runs
    ///     first: the caller may write only a row it may read (the read by key, the session's filters applied). <c>RunAsync</c>'s rows are
    ///     not tracked: a declared query's result is read, not loaded for a change.
    /// </summary>
    private static void AppendRepository(StringBuilder text, INamedTypeSymbol entity, string type)
    {
        const string task = "global::System.Threading.Tasks.Task";
        const string ct = "global::System.Threading.CancellationToken ct = default";
        const string spec = "global::Pragmatic.Specification.ISpecification";
        text.AppendLine();
        text.AppendLine($"    /// <summary>Pragmatic's repository for {entity.Name} on the Sql engine: the reads tracked by the unit of work, the writes staged in it.</summary>");
        text.AppendLine($"    public sealed class SqlRepository(global::Pragmatic.Persistence.Sql.Pragmatic.SqlUnitOfWork unitOfWork) : global::Pragmatic.Persistence.Repository.IRepository<{type}>");
        text.AppendLine("    {");
        text.AppendLine("        private readonly SqlReadRepository _read = new(unitOfWork.Session);");
        text.AppendLine();
        text.AppendLine($"        public async {task}<{type}?> GetByIdAsync(global::System.Guid id, {ct})");
        text.AppendLine("            => await _read.GetByIdAsync(id, ct) is { } row ? unitOfWork.Attach(row) : null;");
        text.AppendLine();
        text.AppendLine($"        public async {task}<global::System.Collections.Generic.List<{type}>> FindAsync({spec}<{type}> spec, {ct})");
        text.AppendLine("            => unitOfWork.AttachAll(await _read.FindAsync(spec, ct));");
        text.AppendLine();
        text.AppendLine($"        public {task}<int> CountAsync({spec}<{type}> spec, {ct}) => _read.CountAsync(spec, ct);");
        text.AppendLine();
        text.AppendLine($"        public {task}<bool> ExistsAsync({spec}<{type}> spec, {ct}) => _read.ExistsAsync(spec, ct);");
        text.AppendLine();
        text.AppendLine($"        public async {task}<{type}?> FirstOrDefaultAsync({spec}<{type}> spec, {ct})");
        text.AppendLine("            => await _read.FirstOrDefaultAsync(spec, ct) is { } row ? unitOfWork.Attach(row) : null;");
        text.AppendLine();
        text.AppendLine($"        public global::System.Linq.IQueryable<{type}> Query() => _read.Query();");
        text.AppendLine();
        text.AppendLine($"        public {task}<global::System.Collections.Generic.IReadOnlyList<TResult>> RunAsync<TResult>(global::Pragmatic.Persistence.Query.Interfaces.IQuery<{type}, TResult> query, {ct}) where TResult : class => _read.RunAsync(query, ct);");
        text.AppendLine();
        text.AppendLine($"        public {task}<global::Pragmatic.Persistence.Query.Results.PagedResult<TResult>> RunAsync<TResult>(global::Pragmatic.Persistence.Query.Interfaces.IPagedQuery<{type}, TResult> query, {ct}) where TResult : class => _read.RunAsync(query, ct);");
        text.AppendLine();
        text.AppendLine($"        public void Add({type} entity) => unitOfWork.Add(entity);");
        text.AppendLine();
        text.AppendLine($"        public void AddRange(global::System.Collections.Generic.IEnumerable<{type}> entities) {{ foreach (var entity in entities) unitOfWork.Add(entity); }}");
        text.AppendLine();
        text.AppendLine($"        public void Update({type} entity) => unitOfWork.Update(entity, Readable(entity));");
        text.AppendLine();
        text.AppendLine($"        public void Remove({type} entity) => unitOfWork.Remove(entity, Readable(entity));");
        text.AppendLine();
        text.AppendLine($"        public void RemoveRange(global::System.Collections.Generic.IEnumerable<{type}> entities) {{ foreach (var entity in entities) unitOfWork.Remove(entity, Readable(entity)); }}");
        text.AppendLine();
        text.AppendLine("        /// <summary>The check a row staged without a read gets: the caller reads it by key, filtered.</summary>");
        text.AppendLine($"        private global::System.Func<global::System.Threading.CancellationToken, {task}<bool>> Readable({type} entity)");
        text.AppendLine("        {");
        text.AppendLine("            var key = entity.PersistenceId;");
        text.AppendLine("            return async ct => await _read.GetByIdAsync(key, ct) is not null;");
        text.AppendLine("        }");
        text.AppendLine("    }");
    }

    /// <summary>One declared query's case: its filters through Matching, its sorts through OrderedBy, its result projected, its page taken and counted.</summary>
    private static void RunCase(StringBuilder text, string type, PragmaticQuery query)
    {
        var name = "global::" + query.Type.ToDisplayString();
        if (query.Unsupported is { } why)
        {
            text.AppendLine($"                case {name}:");
            text.AppendLine($"                    throw new global::System.NotSupportedException({SqlInterceptorGenerator.Literal($"{query.Type.Name} is not compiled for the Sql engine: {why}.")});");
            return;
        }

        var result = "global::" + query.Result.ToDisplayString();
        var project = SymbolEqualityComparer.Default.Equals(query.Result, query.Entity) ? "" : $".Project<{result}>()";
        var filtered = $"session.Query<{type}>().Matching(global::Pragmatic.Persistence.Sql.Pragmatic.SqlSpecifications.ToPredicate(q.ToSpecification()))";
        text.AppendLine($"                case {name} q:");
        text.AppendLine("                {");
        if (query.Paged)
        {
            text.AppendLine($"                    var paged = (global::Pragmatic.Persistence.Query.Interfaces.IPagedQuery<{type}>)q;");
            text.AppendLine($"                    var rows = await {filtered}.OrderedBy(q.ToSqlOrdering()){project}.Skip(paged.Skip).Take(paged.Take).ToListAsync(ct);");
            text.AppendLine($"                    var total = await {filtered}.CountAsync(ct);");
            text.AppendLine($"                    return (global::Pragmatic.Persistence.Query.Results.PagedResult<TResult>)(object)global::Pragmatic.Persistence.Query.Results.PagedResult<{result}>.Success(rows, total, paged.Page, paged.PageSize);");
        }
        else
        {
            text.AppendLine($"                    var rows = await {filtered}.OrderedBy(q.ToSqlOrdering()){project}.ToListAsync(ct);");
            text.AppendLine("                    return (global::System.Collections.Generic.IReadOnlyList<TResult>)(object)rows;");
        }

        text.AppendLine("                }");
    }
}
