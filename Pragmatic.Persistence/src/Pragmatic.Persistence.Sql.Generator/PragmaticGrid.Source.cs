using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Pragmatic.Persistence.Sql.Generator;

/// <summary>
///     The grid's source: <c>ToSpecification(filter)</c>, the DevExpress filter as a specification (a group, a negation, a clause; every part a
///     predicate or a refusal, never nothing, as Pragmatic's adapter answers); <c>LoadAsync(session, options)</c>, the page read through the
///     session's filters with its sort, its skip and take, its total when asked. The clauses are <c>Spec&lt;T&gt;.Where</c> lambdas over typed
///     values, one per field and operator, so EF Core reads the same specification through <c>ToExpression()</c>.
/// </summary>
internal sealed partial class PragmaticGrid
{
    private const string Adapters = "global::Pragmatic.Persistence.Query.Adapters";

    private string EntityName => "global::" + Entity.ToDisplayString();

    private string Spec => $"global::Pragmatic.Specification.Spec<{EntityName}>";

    private string Specification => $"global::Pragmatic.Specification.Specification<{EntityName}>";

    /// <summary>
    ///     The adapter's half an engine declares (hint name, text): the specification and its parsing here (engine-neutral, linked by the documents
    ///     generator), the page read (<paramref name="load" />) and the sort's ordering (<paramref name="ordering" />) the engine's own.
    /// </summary>
    internal (string Hint, string Source) SourceText(string package, string engine, Action<StringBuilder> load, Action<StringBuilder> ordering)
    {
        var text = new StringBuilder();
        text.AppendLine($"// <auto-generated/> {package}: a grid adapter of Pragmatic's on the {engine} (PragmaticGrid).");
        text.AppendLine("#nullable enable");
        if (!Type.ContainingNamespace.IsGlobalNamespace)
            text.AppendLine($"namespace {Type.ContainingNamespace.ToDisplayString()};");
        text.AppendLine();
        text.AppendLine($"partial class {Type.Name}");
        text.AppendLine("{");
        text.AppendLine($"    /// <summary>The DevExpress filter as a specification of {Entity.Name}: no filter is every row, a part that cannot apply is refused.</summary>");
        text.AppendLine($"    public static {Specification} ToSpecification(global::System.Collections.Generic.IReadOnlyList<object?>? filter)");
        text.AppendLine("    {");
        text.AppendLine("        var terms = 0;");
        text.AppendLine($"        return filter is {{ Count: > 0 }} ? Parse(filter, ref terms) : {Spec}.True;");
        text.AppendLine("    }");
        text.AppendLine();
        load(text);
        Parse(text);
        Clause(text);
        foreach (var field in Fields.Where(f => f.Filterable))
            FieldFilter(text, field);
        ordering(text);
        Helpers(text);
        text.AppendLine("}");
        return ($"{Type.ToDisplayString().Replace('.', '_')}.PragmaticGrid.g.cs", text.ToString());
    }

    /// <summary>
    ///     <c>LoadAsync</c>: the filter parsed, the sort ordered, the page read inside the session's filters, its total when asked. The engine
    ///     names its session, its predicate's composition (<paramref name="toPredicate" />), its page type, and whether its count is a long.
    /// </summary>
    internal void LoadText(StringBuilder text, string session, string toPredicate, string page, bool countsInLong)
    {
        var query = $"session.Query<{EntityName}>().Matching(predicate)";
        text.AppendLine($"    /// <summary>The page a DevExpress grid asked for, read inside the session's filters: its rows, and its total when RequireTotalCount.</summary>");
        text.AppendLine($"    public static async global::System.Threading.Tasks.Task<{page}> LoadAsync({session} session, {Adapters}.DevExpressLoadOptions options, global::System.Threading.CancellationToken ct = default)");
        text.AppendLine("    {");
        text.AppendLine("        // Every clause and every sort is a term; past the bound the request is refused before anything is built (GridFilterTooLargeException).");
        text.AppendLine("        var terms = 0;");
        text.AppendLine($"        var specification = options.Filter is {{ Count: > 0 }} filter ? Parse(filter, ref terms) : {Spec}.True;");
        text.AppendLine("        var ordering = Ordering(options.Sort, ref terms);");
        text.AppendLine($"        var predicate = {toPredicate}(specification);");
        text.AppendLine("        var skip = options.Skip ?? 0;");
        text.AppendLine("        var rows = options.Take is { } take");
        text.AppendLine($"            ? await {query}.OrderedBy(ordering).Skip(skip).Take(take).ToListAsync(ct)");
        text.AppendLine($"            : await {query}.OrderedBy(ordering).Skip(skip).ToListAsync(ct);");
        var count = countsInLong ? $"checked((int)await {query}.CountAsync(ct))" : $"await {query}.CountAsync(ct)";
        text.AppendLine($"        int? total = options.RequireTotalCount ? {count} : null;");
        text.AppendLine($"        return new {page}(rows, total);");
        text.AppendLine("    }");
        text.AppendLine();
    }

    private void Parse(StringBuilder text)
    {
        text.AppendLine($"    private static {Specification} Parse(global::System.Collections.Generic.IReadOnlyList<object?> filter, ref int terms)");
        text.AppendLine("    {");
        if (!Nested)
        {
            text.AppendLine("        // Without nested filters a filter is one clause; a group is refused, not ignored.");
            text.AppendLine("        if (filter.Count != 3 || Unwrap(filter[0]) is not string field)");
            text.AppendLine("            throw Malformed();");
            text.AppendLine("        terms = CountedTerms(terms + 1);");
            text.AppendLine("        return Clause(field, Unwrap(filter[1]) as string, Unwrap(filter[2]));");
            text.AppendLine("    }");
            text.AppendLine();
            return;
        }

        text.AppendLine("        // A group of one: the clause or the group it holds. A filter builder wraps a single condition this way.");
        text.AppendLine("        if (filter.Count == 1 && Group(filter[0]) is { } only)");
        text.AppendLine("            return Parse(only, ref terms);");
        text.AppendLine("        if (filter.Count == 2 && Unwrap(filter[0]) is \"!\" && Group(filter[1]) is { } negated)");
        text.AppendLine("            return !Parse(negated, ref terms);");
        text.AppendLine("        if (filter.Count == 3 && Unwrap(filter[0]) is string field && field is not (\"and\" or \"or\" or \"!\"))");
        text.AppendLine("        {");
        text.AppendLine("            terms = CountedTerms(terms + 1);");
        text.AppendLine("            return Clause(field, Unwrap(filter[1]) as string, Unwrap(filter[2]));");
        text.AppendLine("        }");
        text.AppendLine();
        text.AppendLine("        // A composite: [group, \"and\"/\"or\", group, ...], ending on a group.");
        text.AppendLine("        if (filter.Count >= 3 && filter.Count % 2 == 1)");
        text.AppendLine("        {");
        text.AppendLine("            var combined = Parse(GroupAt(filter, 0), ref terms);");
        text.AppendLine("            for (var i = 1; i < filter.Count; i += 2)");
        text.AppendLine("            {");
        text.AppendLine("                var connective = (Unwrap(filter[i]) as string)?.ToLowerInvariant();");
        text.AppendLine("                if (connective is not (\"and\" or \"or\"))");
        text.AppendLine("                    throw Malformed();");
        text.AppendLine("                var next = Parse(GroupAt(filter, i + 1), ref terms);");
        text.AppendLine("                combined = connective == \"and\" ? combined & next : combined | next;");
        text.AppendLine("            }");
        text.AppendLine();
        text.AppendLine("            return combined;");
        text.AppendLine("        }");
        text.AppendLine();
        text.AppendLine("        throw Malformed();");
        text.AppendLine("    }");
        text.AppendLine();
    }

    /// <summary>The field first, so neither the operator nor the value says whether a withheld column exists.</summary>
    private void Clause(StringBuilder text)
    {
        text.AppendLine($"    private static {Specification} Clause(string field, string? op, object? value)");
        text.AppendLine("    {");
        text.AppendLine("        if (!IsFilterable(field))");
        text.AppendLine("            throw RejectedField(field);");
        text.AppendLine("        if (op is null)");
        text.AppendLine("            throw Unsupported(field, op);");
        text.AppendLine("        return field.ToLowerInvariant() switch");
        text.AppendLine("        {");
        foreach (var field in Fields.Where(f => f.Filterable))
            text.AppendLine($"            \"{field.Json.ToLowerInvariant()}\" => Filter_{field.Property}(field, op, value),");
        text.AppendLine("            _ => throw RejectedField(field),");
        text.AppendLine("        };");
        text.AppendLine("    }");
        text.AppendLine();
    }

    private void FieldFilter(StringBuilder text, Field field)
    {
        var e = $"e.{field.Property}";
        text.AppendLine($"    private static {Specification} Filter_{field.Property}(string field, string op, object? value)");
        text.AppendLine("    {");
        if (field.Operators is { Count: > 0 } allowed && Aliases(allowed) is { Count: > 0 } admitted)
        {
            text.AppendLine($"        if (op.ToLowerInvariant() is not ({string.Join(" or ", admitted.Select(t => PragmaticNames.Literal(t)))}))");
            text.AppendLine("            throw Unsupported(field, op);");
        }

        // Against null only equality and inequality mean something, on a column that can hold it.
        text.AppendLine("        if (Unwrap(value) is null)");
        if (field.Kind != Category.String && !field.Nullable)
            text.AppendLine("            throw Unusable(field);");
        else
        {
            text.AppendLine("            return op.ToLowerInvariant() switch");
            text.AppendLine("            {");
            text.AppendLine($"                \"=\" or \"==\" or \"equals\" => {Spec}.Where(e => {e} == null),");
            text.AppendLine($"                \"<>\" or \"!=\" or \"notequals\" => {Spec}.Where(e => {e} != null),");
            text.AppendLine("                _ => throw Unusable(field),");
            text.AppendLine("            };");
        }

        var read = field.Kind switch
        {
            Category.String => "var typed = Text(value);\n        if (typed is null) throw Unusable(field);",
            Category.Boolean or Category.Numeric => $"if (!TryConvert<{field.Type}>(value, out var typed)) throw Unusable(field);",
            Category.DateTime when field.Type == "global::System.DateTimeOffset" => "if (!TryDateTimeOffset(value, out var typed)) throw Unusable(field);",
            Category.DateTime => $"if (!TryConvert<{field.Type}>(value, out var typed)) throw Unusable(field);",
            Category.Guid => "if (!TryGuid(value, out var typed)) throw Unusable(field);",
            Category.Enum => $"if (!TryEnum<{field.Type}>(value, out var typed)) throw Unusable(field);",
            _ => null,
        };
        if (read is null)
        {
            text.AppendLine("        throw Unsupported(field, op);");
            text.AppendLine("    }");
            text.AppendLine();
            return;
        }

        text.AppendLine("        " + read);
        text.AppendLine("        return op.ToLowerInvariant() switch");
        text.AppendLine("        {");
        var arms = new List<(string Tokens, string Condition)>
        {
            ("\"=\" or \"==\" or \"equals\"", $"{e} == typed"),
            ("\"<>\" or \"!=\" or \"notequals\"", $"{e} != typed"),
        };
        if (field.Kind == Category.String)
        {
            arms.Add(("\"contains\"", $"{e} != null && {e}.Contains(typed)"));
            arms.Add(("\"notcontains\"", $"{e} == null || !{e}.Contains(typed)"));
            arms.Add(("\"startswith\"", $"{e} != null && {e}.StartsWith(typed)"));
            arms.Add(("\"endswith\"", $"{e} != null && {e}.EndsWith(typed)"));
        }
        else if (field.Kind is Category.Numeric or Category.DateTime)
        {
            arms.Add(("\">\" or \"gt\"", $"{e} > typed"));
            arms.Add(("\">=\" or \"gte\"", $"{e} >= typed"));
            arms.Add(("\"<\" or \"lt\"", $"{e} < typed"));
            arms.Add(("\"<=\" or \"lte\"", $"{e} <= typed"));
        }

        foreach (var (tokens, condition) in arms)
            text.AppendLine($"            {tokens} => {Spec}.Where(e => {condition}),");
        text.AppendLine("            _ => throw Unsupported(field, op),");
        text.AppendLine("        };");
        text.AppendLine("    }");
        text.AppendLine();
    }

    /// <summary>
    ///     The sort: a column the adapter does not sort on is passed over, as Pragmatic's adapter passes it; the key last is the fallback. The engine
    ///     names its ordering type, its key type and how a key is built from a property (<paramref name="keyOf" />).
    /// </summary>
    internal void OrderingText(StringBuilder text, string ordering, string key, Func<string, string> keyOf)
    {
        var sortable = Fields.Where(f => f.Sortable).ToList();
        text.AppendLine($"    private static {ordering} Ordering(global::System.Collections.Generic.IReadOnlyList<{Adapters}.DevExpressSortDescriptor>? sort, ref int terms)");
        text.AppendLine("    {");
        text.AppendLine($"        var ordering = {ordering}.By(__OrderBy_PersistenceId);");
        text.AppendLine("        if (sort is null)");
        text.AppendLine("            return ordering;");
        text.AppendLine("        terms = CountedTerms(terms + sort.Count);");
        text.AppendLine("        foreach (var descriptor in sort)");
        text.AppendLine("        {");
        text.AppendLine("            var key = descriptor.Selector?.ToLowerInvariant() switch");
        text.AppendLine("            {");
        foreach (var field in sortable)
            text.AppendLine($"                \"{field.Json.ToLowerInvariant()}\" => __OrderBy_{field.Property},");
        text.AppendLine("                _ => null,");
        text.AppendLine("            };");
        text.AppendLine("            if (key is not null)");
        text.AppendLine("                ordering = ordering.Then(key, descriptor.Desc);");
        text.AppendLine("        }");
        text.AppendLine();
        text.AppendLine("        return ordering;");
        text.AppendLine("    }");
        text.AppendLine();
        foreach (var column in sortable.Select(f => f.Property).Append("PersistenceId").Distinct())
            text.AppendLine($"    private static readonly {key} __OrderBy_{column} = {keyOf(column)};");
        text.AppendLine();
    }

    /// <summary>
    ///     The operator names a <c>[GridField(AllowedOperators)]</c> restriction covers, with their aliases, as Pragmatic's template expands them:
    ///     a restriction to "equals" also admits "=" and "==".
    /// </summary>
    private static List<string> Aliases(IReadOnlyList<string> allowed)
    {
        string[][] groups =
        [
            ["=", "==", "equals"], ["<>", "!=", "notequals"], ["contains"], ["notcontains"], ["startswith"], ["endswith"],
            [">", "gt", "greaterthan"], [">=", "gte", "greaterthanorequal"], ["<", "lt", "lessthan"], ["<=", "lte", "lessthanorequal"],
        ];
        var tokens = new List<string>();
        foreach (var name in allowed.Select(a => a.ToLowerInvariant()))
        {
            var group = groups.FirstOrDefault(g => Array.IndexOf(g, name) >= 0) ?? [name];
            tokens.AddRange(group.Where(t => !tokens.Contains(t)));
        }

        return tokens;
    }
}
