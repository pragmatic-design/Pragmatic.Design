        source.Should().Contain("partial class Order");
    }

    [Fact]
    public void Entity_WithRequiredProperties_IncludesParameters()
    {
        // Arrange
        var model = CreateBasicModel() with
        {
            Properties = ImmutableArray.Create(
                new PropertyMetadataModel
                {
                    Name = "CustomerName",
                    TypeName = "string",
                    IsRequiredForCreate = true
                },
                new PropertyMetadataModel
                {
                    Name = "Amount",
                    TypeName = "decimal",
                    IsRequiredForCreate = true
                }
            )
        };

        // Act
        var template = new EntityCreateTemplate(model);
        var artifact = template.RenderOutput();

        // Assert
        var source = artifact.Text;

        source.Should().Contain("customerName");
        source.Should().Contain("amount");
    }

