using System.Collections.Immutable;
using Pragmatic.Testing.Assertions;
using Pragmatic.SourceGenerator.Features.Persistence.Models;
using Pragmatic.SourceGenerator.Features.Persistence.Templates;
using Xunit;

namespace Pragmatic.Persistence.EFCore.Tests.Templates;

/// <summary>
///     Tests for the EntityCreateTemplate which generates static Create factory methods on entities.
/// </summary>
public class EntityCreateTemplateTests
{
    [Fact]
    public void SimpleEntity_GeneratesCreateMethod()
    {
        // Arrange
        var model = CreateBasicModel();

        // Act
        var template = new EntityCreateTemplate(model);
        var artifact = template.RenderOutput();

        // Assert
        artifact.IsEmpty.Should().BeFalse();
        var source = artifact.Text;

        source.Should().Contain("static");
        source.Should().Contain("Create");
    }

    [Fact]
    public void SimpleEntity_GeneratesPartialClass()
    {
        // Arrange
        var model = CreateBasicModel();

        // Act
        var template = new EntityCreateTemplate(model);
        var artifact = template.RenderOutput();

        // Assert
