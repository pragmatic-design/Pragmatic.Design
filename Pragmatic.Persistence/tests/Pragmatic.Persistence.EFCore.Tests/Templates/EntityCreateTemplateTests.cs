    [Fact]
    public void Entity_WithNullableProperty_ExcludesFromCreate()
    {
        // Arrange
        var model = CreateBasicModel() with
        {
            Properties = ImmutableArray.Create(
                new PropertyMetadataModel
                {
                    Name = "CustomerName",
