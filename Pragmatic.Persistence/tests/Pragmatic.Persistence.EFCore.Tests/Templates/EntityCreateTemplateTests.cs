    [Fact]
    public void RealisticScenario_OrderEntity()
    {
        // Arrange - Full order entity with multiple properties
        var model = new EntityMetadataModel
        {
            TypeName = "Order",
            FullTypeName = "Contoso.Sales.Entities.Order",
            Namespace = "Contoso.Sales.Entities",
            IdType = "System.Guid",
            IsAuditable = true,
            IsSoftDelete = true,
            Properties = ImmutableArray.Create(
                new PropertyMetadataModel
                {
                    Name = "OrderNumber",
                    TypeName = "string",
                    IsRequiredForCreate = true
                },
                new PropertyMetadataModel
                {
                    Name = "CustomerId",
                    TypeName = "System.Guid",
                    IsRequiredForCreate = true
                },
                new PropertyMetadataModel
                {
                    Name = "TotalAmount",
                    TypeName = "decimal",
                    IsRequiredForCreate = true
                },
                new PropertyMetadataModel
                {
                    Name = "Notes",
                    TypeName = "string?",
                    IsNullable = true,
                    IsRequiredForCreate = false
                }
            )
        };

        // Act
        var template = new EntityCreateTemplate(model);
        var artifact = template.RenderOutput();

        // Assert
        var source = artifact.Text;

        source.Should().Contain("namespace Contoso.Sales.Entities;");
        source.Should().Contain("partial class Order");
        source.Should().Contain("Create");
        source.Should().Contain("orderNumber");
        source.Should().Contain("customerId");
        source.Should().Contain("totalAmount");
        source.Should().Contain("Guid.CreateVersion7()");
        source.Should().Contain("CreatedAt");
        source.Should().Contain("IsDeleted");
    }

    private static EntityMetadataModel CreateBasicModel()
    {
        return new EntityMetadataModel
        {
            TypeName = "Order",
            FullTypeName = "MyApp.Sales.Entities.Order",
            Namespace = "MyApp.Sales.Entities",
            IdType = "System.Guid",
            Properties = ImmutableArray.Create(
                new PropertyMetadataModel
                {
                    Name = "OrderNumber",
                    TypeName = "string",
                    IsRequiredForCreate = true
                }
            )
        };
    }
}
