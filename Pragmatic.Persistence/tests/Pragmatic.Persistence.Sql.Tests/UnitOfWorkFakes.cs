using Pragmatic.Events;
using Pragmatic.Persistence.Lifecycle;
using Pragmatic.Persistence.Sql;

namespace PragmaticEntities.Tests;

/// <summary>A clock that stands still: the stamps a save writes are known.</summary>
internal sealed class FixedClock(DateTimeOffset now) : TimeProvider
{
    public override DateTimeOffset GetUtcNow() => now;
}

/// <summary>A dispatcher that keeps what it is handed, and whether a save's transaction was still open then.</summary>
internal sealed class RecordingDispatcher : IDomainEventDispatcher
{
    public List<IDomainEvent> Dispatched { get; } = [];

    public Task DispatchAsync<TEvent>(TEvent @event, CancellationToken ct = default) where TEvent : IDomainEvent
    {
        Dispatched.Add(@event);
        return Task.CompletedTask;
    }

    public Task DispatchAsync(IEnumerable<IDomainEvent> events, CancellationToken ct = default)
    {
        Dispatched.AddRange(events);
        return Task.CompletedTask;
    }
}

/// <summary>A module's phase, as the audit log's would be: one amenity row per saved entity, written with them.</summary>
internal sealed class JournalPhase : ISqlSavePhase
{
    public ValueTask ApplyAsync(SqlSaveContext save, CancellationToken ct)
    {
        foreach (var entry in save.Entries)
            save.Batch.InsertAsIs(new Amenity { Name = $"journal:{entry.Entity.GetType().Name}:{entry.State}" });
        return ValueTask.CompletedTask;
    }
}

/// <summary>A <c>[GeneratedValue]</c> on Review.Text: filled when empty, never over a value the caller gave.</summary>
internal sealed class ReviewTextBinding : IGeneratedValueBinding
{
    public Type EntityType => typeof(Review);

    public string PropertyName => nameof(Review.Text);

    public Task<bool> TryFillAsync(object entity, LifecycleContext context, CancellationToken ct)
    {
        if (entity is not Review { Text: "" } review)
            return Task.FromResult(false);
        review.Text = $"generated by {context.UserId} at {context.Now:yyyy-MM-dd}";
        return Task.FromResult(true);
    }
}
