    /// <summary>
    ///     Emits <c>ParentVisibilityFilter</c> on a trait child whose parent restricts rows.
    /// </summary>
    private static void GenerateParentVisibilityFilter(
        SourceProductionContext ctx,
        string parentNamespace,
        string childTypeName,
        string parentTypeName,
        string? boundaryName,
        bool isOwned,
        bool isScoped)
    {
        var template = new Templates.TraitParentVisibilityFilterTemplate(
            new Templates.TraitParentVisibilityModel(
                parentNamespace,
                childTypeName,
                parentTypeName,
                parentTypeName,                       // the reference navigation is named after the parent
                BypassPermissionFor(boundaryName, parentTypeName),
                isOwned,
                isScoped));

        var artifact = template.RenderOutput();
        if (!artifact.IsEmpty)
            ctx.AddSource(artifact);
    }

    /// <summary>
    ///     The parent's own bypass permission, rebuilt exactly as <c>DataAccessFilterTemplate</c>
    ///     builds it: whoever may see every parent may list every child.
    /// </summary>
    private static string BypassPermissionFor(string? boundaryName, string parentTypeName)
    {
        var kebab = PermissionNaming.ToKebabCase(parentTypeName);
        return string.IsNullOrEmpty(boundaryName)
            ? $"{kebab}.view-all"
            : $"{boundaryName!.ToLowerInvariant()}.{kebab}.view-all";
    }

