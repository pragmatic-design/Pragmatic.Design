using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using Pragmatic.SourceGen;

namespace Pragmatic.SourceGenerator.Features.Composition.Generators;

/// <summary>
///     Emits the zero-reflection HostTopology metadata provider: an <c>IAssemblyMetadataProvider</c>
///     implementation plus a module initializer that registers it with <c>AssemblyMetadataRegistry</c>.
///     This makes <c>HostTopologyInfo.FromRegistry()</c> return the real topology at runtime (no assembly
///     attribute reflection, AOT-safe), removing the perpetual "falling back to reflection" boot warning.
/// </summary>
internal static partial class HostModeGenerator
{
    private static void GenerateHostTopologyMetadataProvider(
        SourceProductionContext context, string rootNamespace, string topologyJson)
    {
        // Escape identically to the [assembly: PragmaticMetadata] attribute so the registry entry carries
        // byte-for-byte the same JSON that HostTopologyInfo.Parse consumes.
        var escaped = topologyJson.Replace("\\", "\\\\").Replace("\"", "\\\"");

        var ns = string.IsNullOrWhiteSpace(rootNamespace) ? "PragmaticGenerated" : rootNamespace;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// HostTopology metadata provider — zero-reflection registry registration.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        sb.AppendLine("/// <summary>Registers this host's topology with AssemblyMetadataRegistry (AOT-safe).</summary>");
        sb.AppendLine("internal sealed class PragmaticHostTopologyMetadataProvider : global::Pragmatic.Composition.Metadata.IAssemblyMetadataProvider");
        sb.AppendLine("{");
        sb.AppendLine($"    private const string Json = \"{escaped}\";");
        sb.AppendLine();
        sb.AppendLine("    private static readonly global::System.Collections.Generic.IReadOnlyList<global::Pragmatic.Composition.Metadata.AssemblyMetadataEntry> Entries =");
        sb.AppendLine("        new global::Pragmatic.Composition.Metadata.AssemblyMetadataEntry[]");
        sb.AppendLine("        {");
        sb.AppendLine($"            new(global::Pragmatic.Composition.Metadata.MetadataCategory.HostTopology, \"{MetadataSchemaVersions.HostTopology}\", Json),");
        sb.AppendLine("        };");
        sb.AppendLine();
        sb.AppendLine("    public global::System.Collections.Generic.IReadOnlyList<global::Pragmatic.Composition.Metadata.AssemblyMetadataEntry> GetMetadata() => Entries;");
        sb.AppendLine();
        sb.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine("    internal static void Register()");
        sb.AppendLine("        => global::Pragmatic.Composition.Metadata.AssemblyMetadataRegistry.Register(new PragmaticHostTopologyMetadataProvider());");
        sb.AppendLine("}");

        context.AddSource(
            "_Metadata.HostTopology.Registration.g.cs",
            SourceText.From(sb.ToString(), Encoding.UTF8));
    }
}
